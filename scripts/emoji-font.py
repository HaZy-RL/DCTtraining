#!/usr/bin/env python3
"""Build the bundled emoji fallback font: Noto Color Emoji (COLRv1) cut down to the emoji the app actually uses.

Machines without a colour-emoji font (stock Linux + Chrome) otherwise show the app's emoji icons as empty boxes.
The font is last in the CSS font stacks, so systems with their own emoji font never download it.

Rerun after adding new emoji to src/:
  pip install fonttools brotli
  curl -LO https://raw.githubusercontent.com/googlefonts/noto-emoji/main/2D/fonts/Noto-COLRv1-noflags.ttf
  python3 scripts/emoji-font.py path/to/Noto-COLRv1-noflags.ttf

Writes src/assets/fonts/dct-emoji.woff2 and src/emoji-font.css (the @font-face, with a matching unicode-range).
"""
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_FONT = os.path.join(ROOT, 'src', 'assets', 'fonts', 'dct-emoji.woff2')
OUT_CSS = os.path.join(ROOT, 'src', 'emoji-font.css')


def is_emojiish(o: int) -> bool:
    return 0x2190 <= o <= 0x2BFF or 0x1F000 <= o <= 0x1FAFF or o in (0x200D, 0x20E3, 0xFE0F)


def used_codepoints() -> set[int]:
    cps: set[int] = set()
    for root, _, files in os.walk(os.path.join(ROOT, 'src')):
        for f in files:
            if f.endswith(('.ts', '.tsx')):
                with open(os.path.join(root, f), encoding='utf-8') as fh:
                    cps.update(ord(ch) for ch in fh.read() if is_emojiish(ord(ch)))
    return cps


def ranges(cps: list[int]) -> str:
    out, start, prev = [], None, None
    for c in cps + [None]:
        if start is not None and (c is None or c != prev + 1):
            out.append(f'U+{start:X}' if start == prev else f'U+{start:X}-{prev:X}')
            start = None
        if c is not None and start is None:
            start = c
        prev = c
    return ', '.join(out)


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    cmap = TTFont(src)['cmap'].getBestCmap()
    wanted = used_codepoints()
    # Only what the emoji font can draw; arrows, box drawing etc. come from the normal text fonts.
    cps = sorted(c for c in wanted if c in cmap)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']  # keep ZWJ / variation-selector sequences working
    opts.name_IDs = ['*']
    opts.notdef_outline = False
    font = subset.load_font(src, opts)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    os.makedirs(os.path.dirname(OUT_FONT), exist_ok=True)
    subset.save_font(font, OUT_FONT, opts)
    visible = [c for c in cps if c not in (0x200D, 0x20E3, 0xFE0F)]
    with open(OUT_CSS, 'w', encoding='utf-8') as fh:
        fh.write(
            '/* Generated by scripts/emoji-font.py: Noto Color Emoji (SIL OFL 1.1, see src/assets/fonts/NOTO-EMOJI-LICENSE),\n'
            '   subset to the emoji used in src/. Last-resort fallback for systems without a colour-emoji font. */\n'
            '@font-face {\n'
            "  font-family: 'DCT Emoji';\n"
            "  src: url('./assets/fonts/dct-emoji.woff2') format('woff2');\n"
            '  font-display: swap;\n'
            f'  unicode-range: {ranges(cps)};\n'
            '}\n'
        )
    print(f'{len(visible)} emoji ({len(wanted) - len(cps)} other symbols left to the text fonts) → {os.path.relpath(OUT_FONT, ROOT)} ({os.path.getsize(OUT_FONT) // 1024} KB)')


if __name__ == '__main__':
    main()
